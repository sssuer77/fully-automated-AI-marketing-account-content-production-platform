"""画布几何对齐（T3.2 / T4.14）—— 为什么"偶数"这件事值得单独一个模块。

``yuv420p`` 是**色度二次采样**的：U/V 两个平面在横竖两个方向上都只有亮度平面的一半
分辨率。于是 ffmpeg 的 ``overlay`` 把一块图贴在奇数坐标上时，色度平面必须"猜"那半个
像素落在哪 —— 结果是贴着的那条边出现 1px 的色边（合成之后几乎看不出来，直到成片被
平台二次编码放大）。

所以这一层有一个硬不变量：**``overlay`` 的 x/y，以及被贴素材的宽/高，全部取偶**。
水印（``render/watermark.py``）与人物贴图（``render/sticker.py``）都靠它，
口径只写一遍 —— 两处各写一份 ``value - value % 2`` 看着无害，但其中一处哪天被改成
``value - 1`` 或者"向上取偶"，就只有一条链路会出边，而那种差异在 diff 里根本看不出来。
"""

from __future__ import annotations

__all__ = ["even_floor"]


def even_floor(value: int) -> int:
    """向下取到偶数（``-2`` 的语义就是"取偶"）。

    向下而不是就近：向上取偶会让"算出来刚好差 1px"变成**越界**（右下角 x = W - w - m
    已经贴着画布边），而向下最多只是少 1px —— 少 1px 看不出来，越界会直接贴出画面外。
    """
    return value - value % 2
