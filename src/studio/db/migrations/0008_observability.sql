-- ==========================================================================
-- 0008_observability.sql — 观测与保留期要用的两个索引（T4.12 · §03.7.5）
-- 来源：docs/spec/03-data-model.md §3.7.5（数据保留与 GC）+ todolist T4.12 索引项
-- ==========================================================================
-- 为什么是"补两个索引"而不是"加两张表"
-- ------------------------------------
-- T4.12 新增的两件事（保留期 GC、操作审计页）都不需要新列、新表：
--   · GC 要**按时间删旧行**，审计页要**按 source / 人 / 动作筛**；
--   · 两者都是"查询形状缺索引"，不是"数据模型缺字段"。
-- 按 §03.7.2 规则 1（只增不改）与规则 3（幂等），补索引走一个新迁移文件即可。
--
-- ① idx_logs_source —— T4.9 转来的欠账
-- ------------------------------------
-- `LogService._filtered()` 的过滤形状是 `WHERE source = ? ORDER BY id`
-- （§04.5.3 的实时日志面板：按来源过滤 + 按 id 升序回放）。已有的三个索引
-- （`idx_logs_task` / `idx_logs_ts` / `idx_logs_warn`）一个都吃不到 `source`：
-- 前两个前缀不是它，第三个是 `level` 的部分索引。
-- 列序是 `(source, id)` 而不是 `(source, ts)`：**排序键是 `id`**（日志表的主键
-- 即游标，`since_id` 补洞靠它），把 `ts` 放进去会让 `ORDER BY id` 退化成临时 B 树。
-- 当时没落地是因为它牵动 15 处「对象数冻结」断言（§03.7.1 的 29 表 / 58 索引）；
-- T4.12 本来就要动 schema 窗口，一起补上比再开一次窗口便宜。
--
-- ② idx_events_created —— 保留期 GC 的前提
-- ----------------------------------------
-- `task_events` 只有 `idx_events_task(task_id, id)`，而 §03.7.5 要求按 `created_at`
-- 保留 90 天。没有这个索引，每日 GC 就是**全表扫**：一张 90 天量的流水表，
-- 每天扫一次，正好在最该省的地方花钱（GC 是无人值守跑的，没人看着它慢）。
-- --------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_logs_source   ON system_logs(source, id);
CREATE INDEX IF NOT EXISTS idx_events_created ON task_events(created_at);
