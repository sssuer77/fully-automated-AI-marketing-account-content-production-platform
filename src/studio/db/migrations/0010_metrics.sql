-- ==========================================================================
-- 为什么需要一列计数器
-- --------------------
-- §6.6 的失败处置是"顺延 1 小时、最多试 3 次、仍失败就**停止采集这一条**"。
-- 这句话里"试了几次"必须落在库里，理由与 0007 的 `consecutive_oom` 一模一样：
--  ① `metrics_history_json` 只记**成功**的读数（时间序列要能直接画趋势图，
--     掺进失败记录就得让每个读者自己过滤），判不出"连续失败了几次"；
--  ② `system_logs` 是有保留期的日志，拿它当业务状态的载体，等于把
--     "别重复试第四次"建立在"日志还没被 GC"这个前提上。
--
-- 语义（三条）
-- -----------
-- 1. `record_metrics()` ⇒ 归 0：一次成功读数就是"这个时点办完了"，下一时点重新计数；
-- 2. `defer_metrics()` ⇒ +1，并把 `next_metric_at` 顺延 1 小时；
-- 3. 计数到 `METRICS_MAX_ATTEMPTS`（3）的那一次 ⇒ `next_metric_at` 置 NULL
--    （= 停止采集这一条），**不**回退发布状态、**不**碰 `tasks`：
--    数据回收失败不是发布失败（§06.6「不阻塞其他发布」）。
--
-- 为什么不做成"每次失败都写一行历史"
-- ----------------------------------
-- 那会得到一个只增不减的表，而它的读法（"这条作品现在多少播放"）永远只看最后一拍。
-- 计数器只有 1 列、只有 3 个取值，比一张失败日志表诚实得多。
-- --------------------------------------------------------------------------

ALTER TABLE publications ADD COLUMN metric_attempts INTEGER NOT NULL DEFAULT 0;