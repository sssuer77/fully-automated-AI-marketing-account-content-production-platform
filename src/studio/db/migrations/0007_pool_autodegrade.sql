-- 为什么需要一列计数器
-- --------------------
-- "单池连续 N 次 TTS_OOM ⇒ 并发 −1" 这条规则要能回答"**连续**了几次"。两个
-- 现成的数据源都不行：
--   ① `jobs`：一条作业重试三次只留一行（`attempts=3`），"连续 2 次 OOM"与
--      "一条作业 OOM 两次"在表里长得一模一样，判不出来；
--   ② `system_logs`：那是有保留期的日志（§03.7.5 会清理），拿它当**业务状态**
--      的载体，等于把规则建立在"日志还没被 GC"这个前提上。
-- 所以计数器落在 `pool_settings`：它本来就是"池运行时可调参数"的落点，与
-- `concurrency` 同表同事务更新，读一次就够（worker 认领前本来就要读这一行）。
--
-- 语义（三条）
-- -----------
-- 1. `fail(code=TTS_OOM)` ⇒ +1；`succeed()` ⇒ 归 0（"连续"由一次成功打断）；
-- 2. 达到 `pools.yaml → auto_concurrency.oom_threshold` **的那一次**才降并发并告警，
--    之后继续 OOM 只累加不再告警（`==` 判据，不是 `>=`）；
-- 3. 人工重投死信**不**清零：计数器量的是"显存能不能装下"，与某条作业的进度无关。
-- --------------------------------------------------------------------------

ALTER TABLE pool_settings ADD COLUMN consecutive_oom INTEGER NOT NULL DEFAULT 0;
